source("scripts/its.R", encoding = "UTF-8"); its_configure()
d <- read.csv("assets/seatbelts.csv")
prep <- its_prepare(d, "month", "DriversKilled", "1983-02", 12, covariates = c("kms","PetrolPrice"))
print(prep)
ex <- its_explore(prep, "demo_seatbelts/out", "每月駕駛死亡數"); print(ex)
sp <- its_spec(prep, "dummy")
m_ols <- its_fit(prep, sp, "ols", approved = TRUE)
print(its_diagnose(m_ols, prep, out_dir = "demo_seatbelts/out"))
ar <- its_select_ar(prep, sp); print(ar)
m <- its_fit(prep, sp, "gls", ar$best_p, approved = TRUE)
print(its_diagnose(m, prep, out_dir = "demo_seatbelts/out"))
e <- its_effects(m, prep); print(e)
its_plot(m, prep, "demo_seatbelts/out/its_main.png", "每月駕駛死亡數")
print(its_sensitivity(m, prep, covariates = c("kms","PetrolPrice"), transition = 2, pre_window = 96, data = d))
cat(its_explain(e, prep, "每月駕駛死亡數", " 人"), "\n")
